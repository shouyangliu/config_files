local function set_wallpaper(s)
    -- Wallpaper
    if beautiful.wallpaper then
        local wallpaper = beautiful.wallpaper
        -- If wallpaper is a function, call it with the screen
        if type(wallpaper) == "function" then
            wallpaper = wallpaper(s)
        end
        gears.wallpaper.maximized(wallpaper, s, true)
    end
end

-- Re-set wallpaper when a screen's geometry changes (e.g. different resolution)
screen.connect_signal("property::geometry", set_wallpaper)

awful.screen.connect_for_each_screen(function(s)
    -- Wallpaper
    set_wallpaper(s)

    -- Each screen has its own tag table.
    awful.tag({ "1", "2", "3", "4", "5", "6", "7", "8", "9" }, s, awful.layout.layouts[1])

    -- Create a promptbox for each screen
    s.mypromptbox = awful.widget.prompt()
    -- Create an imagebox widget which will contain an icon indicating which layout we're using.
    -- We need one layoutbox per screen.
    s.mylayoutbox = awful.widget.layoutbox(s)
    s.mylayoutbox:buttons(gears.table.join(
                           awful.button({ }, 1, function () awful.layout.inc( 1) end),
                           awful.button({ }, 3, function () awful.layout.inc(-1) end),
                           awful.button({ }, 4, function () awful.layout.inc( 1) end),
                           awful.button({ }, 5, function () awful.layout.inc(-1) end)))
    -- Create a taglist widget
    s.mytaglist = awful.widget.taglist {
        screen  = s,
        filter  = awful.widget.taglist.filter.all,
        buttons = taglist_buttons
    }

    -- Create a tasklist widget
    s.mytasklist = awful.widget.tasklist {
        screen  = s,
        filter  = awful.widget.tasklist.filter.currenttags,
        buttons = tasklist_buttons
    }

    -- 状态栏部件：每个 screen 一份实例，不能共用（会被抢父节点）
    local part = widgets.create()

    -- Create the wibox
    s.mywibox = awful.wibar({ position = "top", screen = s })

    -- 右侧顺序与原 bar.sh 里 xsetroot 拼接的顺序一致：
    -- updates cpu battery mem wlan clock
    local right = wibox.layout.fixed.horizontal()
    right:add(wibox.widget.systray())
    local parts = { part.updates, part.cpu, part.battery, part.mem, part.wlan, part.clock }
    -- 用下标循环而非 ipairs：无电池时 part.battery 是 nil，
    -- 表中间有洞，ipairs 会在洞处直接停下、后面的部件全丢。
    for i = 1, 6 do
        if parts[i] then
            right:add(parts[i])
        end
    end

    -- Add widgets to the wibox
    s.mywibox:setup {
        layout = wibox.layout.align.horizontal,
        { -- Left widgets
            layout = wibox.layout.fixed.horizontal,
            mylauncher,
            s.mytaglist,
            s.mypromptbox,
            s.mylayoutbox,
        },
        s.mytasklist, -- Middle widget
        right,        -- Right widgets
    }
end)
