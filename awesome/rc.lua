-- {{{ Autostart
-- 对应原 chadwm 的 scripts/run.sh，逐条搬过来。
-- AWESOME_NO_AUTOSTART=1 时整段跳过 —— awesome/install.sh 的 Xephyr 冒烟测试
-- 用这个开关，免得测试时把 picom / feh / fcitx5 真拉起来、干扰你正在用的会话。
if not os.getenv("AWESOME_NO_AUTOSTART") then
    -- 必须走 with_shell：这里用到了 ~ 展开、||、&、[ ] 这些 shell 语法，
    -- 而 awful.spawn 的字符串形式只做分词、不过 shell。
    --
    -- 有两个坑要绕开：
    -- 1. Super+Shift+R 重启 awesome 会把整个 rc.lua 重跑一遍，所以不能把
    --    `brightnessctl set 10%` 裸放 —— 那样每次重启都会把亮度拍回 10%。
    --    用一个跟会话绑定的标记文件挡一道（XDG_RUNTIME_DIR 注销即清）。
    --    awful.spawn.once 在这里帮不上忙：它的去重表在 Lua 侧，重启后是空的。
    -- 2. picom / fcitx5 改用 pgrep 自愈式判断，而不是上面的标记文件：
    --    万一进程崩了，下次重启还能拉起来；也不会有标记残留导致起不来的问题。
    awful.spawn.with_shell([[
        marker="${XDG_RUNTIME_DIR:-/tmp}/awesome-session-init"

        xrdb merge ~/.Xresources
        xset r rate 200 50

        pgrep -x picom  >/dev/null || picom --config ~/.picom.conf &
        pgrep -x fcitx5 >/dev/null || fcitx5 -d &

        [ -e "$marker" ] || { touch "$marker"; brightnessctl set 10%; }

        feh --randomize --bg-fill ~/.config/wallpaper/
    ]])
end
-- }}}